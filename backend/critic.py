"""
Critic and verification for CrisisSentinel.

Two layers, in order:
  1. Deterministic checks (pure Python, no model): every number and every
     supplier/PO reference in the brief is re-verified against the SQL result.
  2. One adversarial model call (Nemotron Super) that challenges assumptions
     the code cannot check, such as supplier capacity or logistics.

The verdict is computed from real findings. Nothing here invents a score or
claims verification that did not happen.
"""

import json
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, ConfigDict

from llm_json import chat_json

CONCENTRATION_THRESHOLD = 0.6


class Check(BaseModel):
    id: str
    label: str
    passed: bool
    detail: str = ""


class Challenge(BaseModel):
    target: str
    issue_type: str
    severity: str  # low | medium | high
    explanation: str
    suggested_fix: str = ""
    origin: str = "model"  # "model" | "deterministic"


class CritiqueReport(BaseModel):
    model_config = ConfigDict(protected_namespaces=())

    checks: List[Check]
    deterministic_flags: List[str]
    challenges: List[Challenge]
    verdict: str  # accept | revise | escalate | unverified
    status: str = "model"  # "model" | "degraded" (critic model unavailable)
    model_used: Optional[str] = None
    revised: bool = False


def _as_dict(obj: Any) -> Dict[str, Any]:
    return obj.model_dump() if hasattr(obj, "model_dump") else dict(obj)


def run_deterministic_checks(brief: Dict[str, Any], exposure: Dict[str, Any]) -> List[Check]:
    """Re-verify the brief against the SQL result. Pure function."""
    checks: List[Check] = []
    pos = {p["po_id"]: p for p in exposure.get("affected_open_pos", []) if "po_id" in p}
    pairs = {(a["po_id"], a["alt_supplier_id"]) for a in exposure.get("mitigation_alternatives", [])}
    actions = brief.get("recommended_actions", []) or []

    erp_total = float(exposure.get("total_exposure_eur") or 0.0)
    brief_total = float(brief.get("financial_risk_eur") or 0.0)
    checks.append(Check(
        id="total_matches_sql", label="Value at risk equals the SQL total",
        passed=abs(erp_total - brief_total) <= 1.0,
        detail=f"brief €{brief_total:,.2f} vs SQL €{erp_total:,.2f}",
    ))

    runway = exposure.get("critical_runway_days")
    deadline = brief.get("assembly_line_deadline_days")
    if runway is not None:
        ok = deadline is not None and abs(float(runway) - float(deadline)) <= 0.1
        checks.append(Check(
            id="deadline_matches_runway", label="Deadline equals the shortest inventory runway",
            passed=ok, detail=f"brief {deadline} d vs SQL {runway} d",
        ))

    unknown = [a.get("po_id") for a in actions if a.get("po_id") not in pos]
    checks.append(Check(
        id="actions_reference_exposed_pos", label="Every action targets an exposed open PO",
        passed=not unknown, detail=("unknown PO: " + ", ".join(map(str, unknown))) if unknown else f"{len(actions)} action(s) checked",
    ))

    bad_pairs = [
        f"{a.get('po_id')}→{a.get('target_supplier_id')}"
        for a in actions
        if a.get("action_type") == "reroute_supplier" and (a.get("po_id"), a.get("target_supplier_id")) not in pairs
    ]
    checks.append(Check(
        id="suppliers_are_erp_approved", label="Every reroute uses an ERP-approved alternative for that PO",
        passed=not bad_pairs, detail=("not approved: " + ", ".join(bad_pairs)) if bad_pairs else "all reroute pairs found in alt_supplier_map",
    ))

    mismatched = [
        a.get("po_id") for a in actions
        if a.get("po_id") in pos and (
            a.get("target_plant") != pos[a["po_id"]]["plant_name"]
            or a.get("target_material") != pos[a["po_id"]]["material_id"]
        )
    ]
    checks.append(Check(
        id="plant_material_match_po", label="Action plant and material match the PO record",
        passed=not mismatched, detail=("mismatch on: " + ", ".join(map(str, mismatched))) if mismatched else "consistent with ERP",
    ))

    checks.append(Check(
        id="brief_generated_by_model", label="Plan was generated by the model (not the SQL fallback)",
        passed=brief.get("brief_source") == "nemotron",
        detail=f"brief_source = {brief.get('brief_source', 'unknown')}",
    ))
    return checks


def _concentration_challenge(brief: Dict[str, Any], exposure: Dict[str, Any]) -> Optional[Challenge]:
    names = {a["alt_supplier_id"]: a.get("alt_supplier_name", a["alt_supplier_id"]) for a in exposure.get("mitigation_alternatives", [])}
    by_supplier: Dict[str, float] = {}
    for a in brief.get("recommended_actions", []) or []:
        if a.get("action_type") == "reroute_supplier" and a.get("target_supplier_id"):
            by_supplier[a["target_supplier_id"]] = by_supplier.get(a["target_supplier_id"], 0.0) + float(a.get("value_rerouted_eur") or a.get("estimated_cost_eur") or 0.0)
    total = sum(by_supplier.values())
    if total <= 0 or len(by_supplier) == 0:
        return None
    top_id, top_val = max(by_supplier.items(), key=lambda kv: kv[1])
    share = top_val / total
    if share >= CONCENTRATION_THRESHOLD:
        return Challenge(
            target="Reroute plan", issue_type="single_source_concentration", severity="medium", origin="deterministic",
            explanation=f"{share:.0%} of rerouted order value (€{top_val:,.0f}) lands on {names.get(top_id, top_id)}; a problem there would recreate the exposure.",
            suggested_fix="Confirm the alternative's spare capacity before approving, or split volume across a second qualified supplier.",
        )
    return None


def critique_and_verify(
    brief: Dict[str, Any],
    erp_exposure: Dict[str, Any],
    claims: List[Dict[str, Any]],
    contradictions: List[Dict[str, Any]],
    client,
    model_id: str,
    revised: bool = False,
) -> CritiqueReport:
    brief = _as_dict(brief)
    checks = run_deterministic_checks(brief, erp_exposure)
    flags = [f"{c.label}: {c.detail}" for c in checks if not c.passed and c.id != "brief_generated_by_model"]

    challenges: List[Challenge] = []
    for c in checks:
        if not c.passed and c.id != "brief_generated_by_model":
            challenges.append(Challenge(
                target="Deterministic check", issue_type="numeric_mismatch", severity="high", origin="deterministic",
                explanation=f"{c.label} failed ({c.detail}).",
                suggested_fix="Regenerate the plan from the SQL result.",
            ))
    concentration = _concentration_challenge(brief, erp_exposure)
    if concentration:
        challenges.append(concentration)

    system_prompt = (
        "You are an adversarial supply-chain executive reviewing a crisis mitigation plan for an EV maker.\n"
        "Find genuine weaknesses the code cannot check: supplier capacity, qualification time, logistics, "
        "timeline realism, weak or conflicting evidence. Do not repeat the deterministic findings.\n"
        "Return ONLY JSON: {\"challenges\": [{\"target\": str, \"issue_type\": "
        "\"weak_evidence|unresolved_conflict|unsupported_assumption|missing_alternative\", "
        "\"severity\": \"low|medium|high\", \"explanation\": str, \"suggested_fix\": str}], "
        "\"verdict\": \"accept|revise|escalate\"}\n"
        "Use severity 'high' and verdict 'revise' ONLY for a flaw that would make the plan fail. "
        "If the plan is sound, return an empty challenges list and verdict 'accept'. At most 3 challenges."
    )
    payload = {
        "plan": {
            "headline": brief.get("headline"),
            "actions": [
                {k: a.get(k) for k in ("priority", "title", "action_type", "po_id", "target_supplier_id",
                                       "target_plant", "target_material", "rationale", "value_rerouted_eur")}
                for a in brief.get("recommended_actions", [])
            ],
        },
        "deterministic_check_results": [c.model_dump() for c in checks],
        "evidence_claims": [{"id": c.get("claim_id"), "text": c.get("text")} for c in claims][:6],
        "unresolved_contradictions": [c for c in contradictions if c.get("resolution_status") != "resolved"],
        "exposure_summary": {
            "total_exposure_eur": erp_exposure.get("total_exposure_eur"),
            "open_pos_count": erp_exposure.get("open_pos_count"),
            "critical_runway_days": erp_exposure.get("critical_runway_days"),
        },
    }
    parsed, _, status = chat_json(
        client=client, model=model_id, system_prompt=system_prompt,
        user_prompt=json.dumps(payload, indent=2, default=str), max_tokens=2500, temperature=0.2,
    )

    model_ok = status == "model" and isinstance(parsed, dict)
    if model_ok:
        for ch in (parsed.get("challenges") or [])[:3]:
            if not isinstance(ch, dict):
                continue
            severity = str(ch.get("severity", "medium")).lower()
            challenges.append(Challenge(
                target=str(ch.get("target", "Plan")),
                issue_type=str(ch.get("issue_type", "unsupported_assumption")),
                severity=severity if severity in ("low", "medium", "high") else "medium",
                explanation=str(ch.get("explanation", "")),
                suggested_fix=str(ch.get("suggested_fix", "")),
                origin="model",
            ))

    failed = any(not c.passed and c.id != "brief_generated_by_model" for c in checks)
    has_high = any(c.severity == "high" for c in challenges)
    if failed or has_high:
        verdict = "revise"
    elif not model_ok:
        verdict = "unverified"
    else:
        model_verdict = str(parsed.get("verdict", "accept")).lower()
        verdict = model_verdict if model_verdict in ("accept", "revise", "escalate") else "accept"

    return CritiqueReport(
        checks=checks, deterministic_flags=flags, challenges=challenges, verdict=verdict,
        status="model" if model_ok else "degraded", model_used=model_id if model_ok else None, revised=revised,
    )